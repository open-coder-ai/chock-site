"""CLI: `python -m sitegen --catalog .catalog --out dist`, `serve` and `allowlist`."""

import argparse
import shutil
import sys
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import ClassVar

from . import analytics, sitedata
from . import pages as pages_mod
from .analytics import AnalyticsError
from .catalog import CatalogError, catalog_head
from .model import Site
from .pages import PageError
from .presets import PresetError

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
TEMPLATES = ROOT / "templates"
STATIC = ROOT / "static"
MARKER = ".sitegen-output"
DEFAULT_SOURCE = "https://github.com/open-coder-ai/chock-catalog"


class _Handler(SimpleHTTPRequestHandler):
    """Static file handler that serves 404.html for missing paths."""

    extensions_map: ClassVar[dict[str, str]] = {
        **SimpleHTTPRequestHandler.extensions_map,
        ".woff2": "font/woff2",
    }

    def send_error(
        self, code: int, message: str | None = None, explain: str | None = None
    ) -> None:
        if code == 404:
            page = Path(self.directory) / "404.html"
            if page.is_file():
                body = page.read_bytes()
                self.send_response(404)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
                return
        super().send_error(code, message, explain)


def _pin(name: str) -> str:
    return (ROOT / name).read_text(encoding="utf-8").strip()


def _refuse(msg: str) -> None:
    print(msg, file=sys.stderr)
    raise SystemExit(2)


def _check_out(out: Path) -> None:
    """Output safety (plan section 4): refuse paths that must never be wiped."""
    resolved = out.resolve()
    root = ROOT.resolve()
    if resolved == Path(resolved.anchor):
        _refuse(f"--out {resolved} is a filesystem root; refusing to delete it")
    if resolved == root:
        _refuse(f"--out {resolved} is the repo root; refusing to delete it")
    if resolved == Path.home().resolve():
        _refuse(f"--out {resolved} is your home directory; refusing to delete it")
    if root.is_relative_to(resolved):
        _refuse(f"--out {resolved} is an ancestor of the repo; refusing to delete it")
    if resolved.exists() and not (
        resolved.is_dir()
        and (not any(resolved.iterdir()) or (resolved / MARKER).is_file())
    ):
        _refuse(
            f"--out {resolved} exists, is not empty and lacks {MARKER}; "
            "refusing to delete it"
        )


def _empty(path: Path) -> None:
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    elif path.exists():
        path.unlink()
    path.mkdir(parents=True)


def build(
    catalog: Path, out: Path, source: str, release: str | None, data: Path = DATA
) -> Site:
    """Refuse a catalog at the wrong commit, then write out/ from it and data/."""
    ref = _pin(".catalog-ref")
    head = catalog_head(catalog)
    if head != ref:
        _refuse(
            f"{catalog}: HEAD is {head}, expected {ref} (.catalog-ref). "
            "Checkout the pinned commit or update the pin."
        )
    events = analytics.load(data)
    analytics.check_module(events, ROOT)
    _check_out(out)
    _empty(out)
    if STATIC.is_dir():
        for item in STATIC.iterdir():
            dest = out / item.name
            if item.is_dir():
                shutil.copytree(item, dest)
            else:
                shutil.copy2(item, dest)
    site = sitedata.build_site(
        catalog, ref, _pin(".framework-ref"), source, release, data
    )
    analytics.write_module(events, out / analytics.DIST_ALLOWLIST)
    sitedata.write_site_json(site, out)
    pages_mod.write_css(site, out, STATIC)
    pages_mod.write_pages(site, out, TEMPLATES, data)
    (out / MARKER).write_text("generated by sitegen\n", encoding="utf-8", newline="\n")
    return site


def make_server(site_dir: Path, port: int) -> ThreadingHTTPServer:
    """An http.server on 127.0.0.1 only, serving site_dir; port 0 picks a free port."""
    handler = partial(_Handler, directory=str(site_dir))
    return ThreadingHTTPServer(("127.0.0.1", port), handler)


def _build_parser(prog: str, out_required: bool) -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog=prog)
    parser.add_argument("--catalog", required=True, type=Path)
    parser.add_argument("--out", type=Path, required=out_required, default=Path("dist"))
    parser.add_argument("--catalog-source", default=DEFAULT_SOURCE)
    parser.add_argument("--release")
    return parser


def _run(args: argparse.Namespace) -> Site:
    try:
        return build(args.catalog, args.out, args.catalog_source, args.release)
    except (AnalyticsError, CatalogError, PresetError, PageError) as exc:
        print(exc, file=sys.stderr)
        raise SystemExit(2) from exc


def main(argv: list[str] | None = None) -> int:
    """Build the site, `serve` to build then serve dist/ on 127.0.0.1, or `allowlist` to regenerate it."""
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv[:1] == ["allowlist"]:
        analytics.write_module(analytics.load(DATA), ROOT / analytics.ALLOWLIST)
        print(f"wrote {analytics.ALLOWLIST}")
        return 0
    if argv[:1] == ["serve"]:
        parser = _build_parser("python -m sitegen serve", out_required=False)
        parser.add_argument("--port", type=int, default=8000)
        args = parser.parse_args(argv[1:])
        _run(args)
        server = make_server(args.out, args.port)
        print(
            f"Serving chock.sh locally at http://127.0.0.1:{server.server_address[1]}/ (Ctrl+C to stop)",
            flush=True,
        )
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            pass
        finally:
            server.server_close()
        return 0
    args = _build_parser("python -m sitegen", out_required=True).parse_args(argv)
    _run(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
